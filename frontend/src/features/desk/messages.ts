export function staffFieldMessage(raw: string) {
  if (DETAILS[raw]) return t(DETAILS[raw]);
  if (/must be an email/i.test(raw)) return t("أدخل بريداً صالحاً.");
  if (/should not be empty|must not be empty/i.test(raw)) return t("هذا الحقل مطلوب.");
  if (/must be longer than or equal to \d+/.test(raw)) return t("القيمة أقصر من الحد المطلوب.");
  return t("قيمة هذا الحقل غير صالحة.");
}

export function staffMessage(code: string, detail?: string) {
  const initial = detail?.match(/Initial top-up must be >=\s*([0-9]+(?:\.[0-9]+)?)/);
  if (initial) return firstTopUp(initial[1]);
  if (detail && DETAILS[detail]) return t(DETAILS[detail]);
  return t(MESSAGES[code] ?? "تعذّر تنفيذ الطلب.");
}
