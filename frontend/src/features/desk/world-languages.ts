export function isWorldLanguageCode(value: string): value is WorldLanguageCode {
  return WORLD_LANGUAGE_SET.has(value);
}

export function normalizeLanguageCode(raw: string) {
  const value = raw.trim().toLowerCase();
  if (value === "ar" || value === "arabic") return "ar";
  if (value === "en" || value === "english") return "en";
  return value;
}

export function languageLabel(code: string) {
  const normalized = normalizeLanguageCode(code);
  if (isWorldLanguageCode(normalized)) return LANGUAGE_LABELS_AR[normalized];
  return normalized;
}

export function worldLanguageOptions(exclude?: string) {
  return WORLD_LANGUAGE_CODES.filter((code) => code !== exclude)
    .map((value) => ({ value, label: languageLabel(value) }))
    .sort((a, b) => a.label.localeCompare(b.label, "ar"));
}
