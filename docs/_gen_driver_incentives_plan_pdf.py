# -*- coding: utf-8 -*-
"""Generate the Arabic PDF for the driver incentives / night fare / fuel pricing plan."""
from pathlib import Path

import arabic_reshaper
from bidi.algorithm import get_display
from fpdf import FPDF

OUT = Path(__file__).with_name("DRIVER_INCENTIVES_PLAN.pdf")
FONT = "ArabicUI"
NAVY = (30, 70, 120)
TEAL = (20, 120, 120)


def ar(text: str) -> str:
    return get_display(arabic_reshaper.reshape(text))


class PlanPDF(FPDF):
    def header(self) -> None:
        self.set_font(FONT, "B", 10)
        self.set_text_color(90, 90, 90)
        self.set_x(self.l_margin)
        self.cell(self.epw, 8, ar("برويا — خطة حوافز السائقين والتسعير"), align="R", new_x="LMARGIN", new_y="NEXT")
        self.set_draw_color(210, 210, 210)
        self.line(self.l_margin, self.get_y(), self.l_margin + self.epw, self.get_y())
        self.ln(5)

    def footer(self) -> None:
        self.set_y(-15)
        self.set_font(FONT, "", 8)
        self.set_text_color(130, 130, 130)
        self.cell(0, 10, f"{self.page_no()}/{{nb}}", align="C")

    def wrap(self, text: str, width: float) -> list[str]:
        """Wraps in logical order, then reorders each line, so wrapped RTL lines keep their order."""
        lines: list[str] = []
        current = ""
        for word in text.split():
            candidate = f"{current} {word}" if current else word
            if current and self.get_string_width(ar(candidate)) > width:
                lines.append(current)
                current = word
            else:
                current = candidate
        if current:
            lines.append(current)
        return [ar(line) for line in lines] or [""]

    def rtl(self, text: str, width: float, line_h: float, indent: float = 0) -> None:
        for line in self.wrap(text, width):
            if self.get_y() + line_h > self.page_break_trigger:
                self.add_page()
            self.set_x(self.l_margin + self.epw - indent - width)
            self.cell(width, line_h, line, align="R", new_x="LMARGIN", new_y="NEXT")

    def h1(self, text: str) -> None:
        self.set_font(FONT, "B", 19)
        self.set_text_color(20, 20, 20)
        self.rtl(text, self.epw, 10)
        self.ln(2)

    def h2(self, text: str) -> None:
        if self.get_y() > 245:
            self.add_page()
        self.ln(4)
        self.set_font(FONT, "B", 14)
        self.set_text_color(*NAVY)
        self.rtl(text, self.epw, 8)
        self.set_draw_color(*NAVY)
        self.line(self.l_margin + self.epw - 40, self.get_y(), self.l_margin + self.epw, self.get_y())
        self.ln(2)

    def h3(self, text: str) -> None:
        if self.get_y() > 255:
            self.add_page()
        self.ln(1)
        self.set_font(FONT, "B", 11.5)
        self.set_text_color(*TEAL)
        self.rtl(text, self.epw, 7)

    def p(self, text: str) -> None:
        self.set_font(FONT, "", 10.5)
        self.set_text_color(35, 35, 35)
        self.rtl(text, self.epw, 6.5)
        self.ln(1.2)

    def bullet(self, text: str) -> None:
        self.set_font(FONT, "", 10.5)
        self.set_text_color(35, 35, 35)
        lines = self.wrap(text, self.epw - 6)
        for index, line in enumerate(lines):
            if self.get_y() + 6.5 > self.page_break_trigger:
                self.add_page()
            y = self.get_y()
            if index == 0:
                self.set_xy(self.l_margin + self.epw - 4, y)
                self.cell(4, 6.5, "•", align="R")
            self.set_xy(self.l_margin, y)
            self.cell(self.epw - 6, 6.5, line, align="R", new_x="LMARGIN", new_y="NEXT")
        self.ln(0.4)

    def box(self, text: str, fill=(242, 247, 252)) -> None:
        self.ln(1)
        self.set_font(FONT, "", 10)
        self.set_text_color(40, 40, 40)
        pad = 2.5
        line_h = 6.5
        lines = self.wrap(text, self.epw - 2 * pad)
        height = len(lines) * line_h + 2 * pad
        if self.get_y() + height > self.page_break_trigger:
            self.add_page()
        y0 = self.get_y()
        self.set_fill_color(*fill)
        self.rect(self.l_margin, y0, self.epw, height, style="F")
        self.set_y(y0 + pad)
        for line in lines:
            self.set_x(self.l_margin + pad)
            self.cell(self.epw - 2 * pad, line_h, line, align="R", new_x="LMARGIN", new_y="NEXT")
        self.set_y(y0 + height)
        self.ln(2)

    def table(self, headers: list[str], rows: list[list[str]], widths: list[float]) -> None:
        """Columns are given left-to-right on the page, so the first Arabic column goes last."""
        line_h = 5.6

        def draw(cells: list[str], header: bool = False) -> None:
            self.set_font(FONT, "B" if header else "", 9.5 if header else 9)
            wrapped = [self.wrap(cell, widths[i] - 3) for i, cell in enumerate(cells)]
            max_lines = max(len(lines) for lines in wrapped)
            row_h = max(max_lines * line_h + 3, 9)
            if self.get_y() + row_h > self.page_break_trigger:
                self.add_page()
            y0 = self.get_y()
            x0 = self.l_margin
            if header:
                self.set_fill_color(*NAVY)
                self.set_text_color(255, 255, 255)
            else:
                self.set_text_color(30, 30, 30)
            self.set_draw_color(200, 200, 200)
            for i, lines in enumerate(wrapped):
                x = x0 + sum(widths[:i])
                self.rect(x, y0, widths[i], row_h, style="DF" if header else "D")
                top = y0 + (row_h - len(lines) * line_h) / 2
                for n, line in enumerate(lines):
                    self.set_xy(x + 1.5, top + n * line_h)
                    self.cell(widths[i] - 3, line_h, line, align="C")
            self.set_y(y0 + row_h)

        draw(headers, header=True)
        for row in rows:
            draw(row)
        self.ln(3)


